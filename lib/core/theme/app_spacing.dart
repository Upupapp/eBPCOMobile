/// Centralized spacing scale for the E-BPCO User App. Use these instead of
/// ad-hoc `SizedBox`/`EdgeInsets` magic numbers so gaps stay consistent
/// across screens.
class AppSpacing {
  AppSpacing._();

  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 24;
  static const double xxl = 32;
}
